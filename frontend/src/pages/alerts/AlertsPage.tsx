import { useState } from "react";
import { Link } from "react-router-dom";
import { send } from "@/api/client";
import type { Paged } from "@/api/types";
import { Can } from "@/auth/AuthContext";
import { DataTable, FilterBar, FilterField, Pagination } from "@/components/data";
import { Badge, Button, Card, DescriptionList, Loading, Modal, PageHeader, ReasonDialog, Select, StatusBadge, useToast } from "@/components/ui";
import { useApi } from "@/hooks/useApi";
import { useUrlState } from "@/hooks/useUrlState";
import { fmtDateTime, fmtRelative, humanize } from "@/lib/format";

interface AlertRow { id: number; rule_code: string; rule_name: string; severity: string; title: string; message: string; status: string; related_label: string;
  link: string; first_detected_at: string; last_detected_at: string; occurrence_count: number; condition_cleared_at: string | null; is_live: boolean;
  acknowledged_by_name: string | null; resolved_by_name: string | null; resolution_note: string; context: Record<string, unknown> }
interface AlertDetail extends AlertRow { activity: { id: number; action: string; actor_name: string | null; note: string; at: string }[] }

export default function AlertsPage() {
  const toast = useToast();
  const [state, update, reset] = useUrlState({ page: "1", active: "true", severity: "", rule: "", status: "" });
  const { data, loading, error, reload } = useApi<Paged<AlertRow>>("/alerts/alerts/", { ...state, page_size: 25 });
  const rules = useApi<{ code: string; name: string }[]>("/alerts/rules/");
  const [selected, setSelected] = useState<number | null>(null);
  const [dialog, setDialog] = useState<"" | "resolve" | "dismiss">("");
  const detail = useApi<AlertDetail>(selected ? `/alerts/alerts/${selected}/` : null);
  const act = async (action: string, note = "") => {
    await send("post", `/alerts/alerts/${selected}/${action}/`, { note });
    toast.success(`Alert ${action === "acknowledge" ? "acknowledged" : action === "resolve" ? "resolved" : "dismissed"}`);
    detail.reload(); reload();
  };
  return (
    <div>
      <PageHeader title="Alerts" subtitle="Generated by the configurable rules engine. Each alert explains why it fired and links to the record."
        actions={<Can perm="alerts.evaluate"><Button icon="refresh" onClick={async () => { await send("post", "/alerts/alerts/evaluate/"); toast.success("Rules evaluated"); reload(); }}>Evaluate now</Button></Can>} />
      <Card bodyClass="p-0">
        <FilterBar onReset={reset}>
          <FilterField label="State"><Select value={state.active} onChange={(e) => update({ active: e.target.value })}>
            <option value="true">Active (open / acknowledged)</option><option value="false">Closed (resolved / dismissed)</option><option value="">All</option></Select></FilterField>
          <FilterField label="Severity"><Select value={state.severity} onChange={(e) => update({ severity: e.target.value })}>
            <option value="">All</option>{["CRITICAL", "WARNING", "INFO"].map((s) => <option key={s} value={s}>{humanize(s)}</option>)}</Select></FilterField>
          <FilterField label="Rule" width="w-64"><Select value={state.rule} onChange={(e) => update({ rule: e.target.value })}>
            <option value="">All rules</option>{rules.data?.map((r) => <option key={r.code} value={r.code}>{r.name}</option>)}</Select></FilterField>
        </FilterBar>
        <DataTable rows={data?.results} loading={loading} error={error} onRetry={reload} rowKey={(a) => a.id} caption="Alerts"
          empty={<p className="p-8 text-center text-sm text-muted">No alerts match these filters.</p>}
          columns={[
            { key: "severity", header: "Severity", render: (a) => <StatusBadge status={a.severity} /> },
            { key: "title", header: "Alert", render: (a) => <button className="text-left link" onClick={() => setSelected(a.id)}>{a.title}</button> },
            { key: "rule", header: "Rule", render: (a) => <span className="text-xs text-ink-2">{a.rule_name}</span> },
            { key: "status", header: "Status", render: (a) => <span className="flex gap-1"><StatusBadge status={a.status} />{!a.is_live && <Badge tone="neutral" icon={null}>Cleared</Badge>}</span> },
            { key: "first", header: "First detected", render: (a) => fmtDateTime(a.first_detected_at) },
            { key: "last", header: "Last seen", render: (a) => fmtRelative(a.last_detected_at) },
            { key: "link", header: "Record", render: (a) => a.link ? <Link className="link" to={a.link}>{a.related_label || "Open"}</Link> : "—" },
          ]} />
        {data && <Pagination count={data.count} page={Number(state.page)} pageSize={25} onPage={(p) => update({ page: String(p) }, { resetPage: false })} />}
      </Card>
      <Modal open={!!selected} onClose={() => setSelected(null)} title={detail.data?.title ?? "Alert"} size="lg"
        footer={detail.data && ["OPEN", "ACKNOWLEDGED"].includes(detail.data.status) && <>
          {detail.data.status === "OPEN" && <Button onClick={() => act("acknowledge")}>Acknowledge</Button>}
          <Button onClick={() => setDialog("dismiss")}>Dismiss</Button>
          <Button variant="primary" onClick={() => setDialog("resolve")}>Resolve</Button></>}>
        {!detail.data ? <Loading /> : (
          <div className="space-y-3">
            <p className="text-sm">{detail.data.message}</p>
            <DescriptionList cols={3} items={[["Severity", <StatusBadge key="s" status={detail.data.severity} />], ["Status", <StatusBadge key="st" status={detail.data.status} />],
              ["Rule", detail.data.rule_name], ["First detected", fmtDateTime(detail.data.first_detected_at)], ["Last detected", fmtDateTime(detail.data.last_detected_at)],
              ["Times detected", detail.data.occurrence_count], ["Condition cleared", fmtDateTime(detail.data.condition_cleared_at)],
              ["Related record", detail.data.link ? <Link key="l" className="link" to={detail.data.link} onClick={() => setSelected(null)}>{detail.data.related_label || "Open"}</Link> : "—"],
              ["Resolution", detail.data.resolution_note || "—"]]} />
            <div><p className="mb-1 text-xs font-semibold text-ink-2">History</p>
              <ol className="space-y-1 text-sm">{detail.data.activity.map((h) => (
                <li key={h.id} className="flex gap-2"><span className="w-32 shrink-0 text-xs text-muted">{fmtDateTime(h.at)}</span>
                  <span>{humanize(h.action)}{h.actor_name ? ` by ${h.actor_name}` : " (system)"}{h.note && h.action !== "CREATED" ? ` - ${h.note}` : ""}</span></li>))}</ol></div>
          </div>
        )}
      </Modal>
      <ReasonDialog open={dialog === "resolve"} title="Resolve alert" label="Resolution note" confirmLabel="Resolve" onClose={() => setDialog("")} onConfirm={(n) => act("resolve", n)}
        description="If the condition is still detected at the next evaluation, the alert reopens." />
      <ReasonDialog open={dialog === "dismiss"} title="Dismiss alert" label="Why is no action needed?" confirmLabel="Dismiss" onClose={() => setDialog("")} onConfirm={(n) => act("dismiss", n)}
        description="A dismissed alert stays dismissed until its condition clears; a later recurrence raises a new alert." />
    </div>
  );
}
