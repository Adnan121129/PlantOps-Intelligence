"""Regenerate docs that are derived from code: the KPI dictionary and the role-permission matrix."""
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand

from apps.accounts.roles import PERMISSIONS, Role
from apps.alerts.rules import SPECS as ALERT_SPECS
from apps.analytics.kpis import KPIS
from apps.analytics.reports import REPORTS
from apps.bi.datasets import DATASETS

HEADER = "<!-- Generated by `python manage.py export_docs`. Do not edit by hand. -->\n\n"


def esc(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


class Command(BaseCommand):
    help = "Write docs/KPI_DICTIONARY.md and docs/PERMISSIONS.md from the code definitions."

    def handle(self, *args, **opts):
        docs = Path(settings.REPO_ROOT) / "docs"
        docs.mkdir(exist_ok=True)
        lines = [HEADER, "# KPI dictionary\n\n",
                 "Every KPI shown in the application, the report centre and the BI layer is defined once in "
                 "`backend/apps/analytics/kpis.py`. Period KPIs use an inclusive range of plant-local dates, evaluated "
                 "as the half-open interval `[00:00 date_from, 00:00 date_to + 1 day)`; periods that include today are "
                 "clipped at the current time. Snapshot KPIs describe the current state.\n\n",
                 "| KPI | Code | Unit | Period | Definition | Formula | Source | Notes |\n|---|---|---|---|---|---|---|---|\n"]
        for code, k in KPIS.items():
            lines.append(f"| {esc(k['label'])} | `{code}` | {esc(k['unit'])} | {k['period']} | {esc(k['definition'])} | "
                         f"`{esc(k['formula'])}` | {esc(k['source'])} | {esc(k.get('notes', ''))} |\n")
        lines.append("\n## Alert rules\n\n| Rule | Code | Default severity | Default parameters | Logic |\n|---|---|---|---|---|\n")
        for code, spec in ALERT_SPECS.items():
            params = ", ".join(f"{k}={v}" for k, v in spec.defaults.items()) or "—"
            lines.append(f"| {esc(spec.name)} | `{code}` | {spec.severity} | {params} | {esc(spec.description)} |\n")
        lines.append("\n## Reports\n\n| Report | Code | Permission | Description |\n|---|---|---|---|\n")
        for code, r in REPORTS.items():
            lines.append(f"| {esc(r.title)} | `{code}` | `{r.permission}` | {esc(r.description)} |\n")
        lines.append("\n## BI datasets (schema `bi`)\n\n| View | Description |\n|---|---|\n")
        for name, d in DATASETS.items():
            lines.append(f"| `bi.{name}` | {esc(d['description'])} |\n")
        (docs / "KPI_DICTIONARY.md").write_text("".join(lines))

        roles = list(Role)
        perm_lines = [HEADER, "# Role-permission matrix\n\n",
                      "Enforced server-side by `apps.accounts.permissions.ActionPermission` using "
                      "`backend/apps/accounts/roles.py`. Object-level rules add further restrictions "
                      "(e.g. supervisors review only their assigned units and never their own submissions).\n\n",
                      "| Permission | " + " | ".join(r.label for r in roles) + " |\n",
                      "|---|" + "---|" * len(roles) + "\n"]
        for code, allowed in PERMISSIONS.items():
            perm_lines.append(f"| `{code}` | " + " | ".join("✓" if r.value in allowed else "" for r in roles) + " |\n")
        (docs / "PERMISSIONS.md").write_text("".join(perm_lines))
        self.stdout.write(self.style.SUCCESS("Wrote docs/KPI_DICTIONARY.md and docs/PERMISSIONS.md"))
